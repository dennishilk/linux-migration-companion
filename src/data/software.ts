import type {
  LocalizedText,
  MigrationRisk,
  SoftwareRecord,
  SoftwareRoute
} from "../domain/types";

const reviewedAt = "2026-08-11";

function text(en: string, de: string): LocalizedText {
  return { en, de };
}

function record(
  id: string,
  name: string,
  category: SoftwareRecord["category"],
  routes: SoftwareRoute[],
  baseRisk: Exclude<MigrationRisk, "blocker">,
  blockerWhenEssential: boolean,
  summaryEn: string,
  summaryDe: string,
  verifyEn: string,
  verifyDe: string,
  sourceLabel: string,
  sourceUrl: string
): SoftwareRecord {
  return {
    id,
    name,
    category,
    routes,
    baseRisk,
    blockerWhenEssential,
    scope: routes.some((route) =>
      [
        "compatibility_layer",
        "alternative_workflow",
        "partial_replacement",
        "no_real_equivalent"
      ].includes(route)
    )
      ? "workflow"
      : "application",
    freshness:
      category === "gaming" ||
      category === "hardware" ||
      category === "cloud" ||
      category === "security" ||
      routes.includes("compatibility_layer") ||
      routes.includes("web_option") ||
      routes.includes("manual_verification_required") ||
      routes.includes("partial_replacement") ||
      routes.includes("no_real_equivalent")
        ? "volatile"
        : "stable",
    summary: text(summaryEn, summaryDe),
    verify: text(verifyEn, verifyDe),
    sourceLabel,
    sourceUrl,
    reviewedAt
  };
}

